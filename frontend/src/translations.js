export const getWardOptions = (lang) => {
  const isNe = lang === 'ne';
  const options = [
    {
      value: 'All',
      label: isNe ? 'All Wards (Biratnagar)' : 'All Wards (Biratnagar)',
    },
  ];

  for (let i = 1; i <= 19; i++) {
    const pad = i < 10 ? `0${i}` : `${i}`;
    options.push({
      value: `Ward ${pad}`,
      label: isNe
        ? `वडा ${toDevanagariNumerals(pad)} — विराटनगर`
        : `Ward ${pad} — Biratnagar`,
    });
  }

  return options;
};
